// Copies scene 1's brand pixels into src/hub/brandData.js so the sticker hub (scene 3)
// draws with exactly the same 5x7 font, ลานนภา logo bitmap and haunted-house sprite
// as the home screen. Run after a new scene 1 file (part of `npm run scene1`).
import { readFileSync, writeFileSync } from 'node:fs';
import { scene1SourceFile } from './scene1-characters.mjs';

const src = readFileSync(scene1SourceFile(), 'utf8');

function grab(re, what) {
  const m = src.match(re);
  if (!m) throw new Error(`hub-brand: could not find ${what} in scene 1`);
  return m[1];
}

const font = grab(/const FONT_SRC = (\{[\s\S]*?\n\});/, 'FONT_SRC');
const logo = grab(/const LOGO = (\{ w: \d+, h: \d+, b64: '[^']+' \});/, 'LOGO');
const house = grab(/const HOUSE_B64 = '([^']+)';/, 'HOUSE_B64');
const windows = grab(/const HOUSE_WINDOWS = (\[[^\n]*\]);/, 'HOUSE_WINDOWS');

const out = `// GENERATED by tools/hub-brand.mjs from scene 1 (${scene1SourceFile().split('/').pop()}). Do not edit by hand.
/* eslint-disable */
export const FONT_SRC = ${font};
export const LOGO = ${logo};
export const HOUSE_B64 = '${house}';
export const HOUSE_WINDOWS = ${windows.replace(/c:COL\.magenta/g, "c:'#F02DF0'")};
`;
writeFileSync('src/hub/brandData.js', out);
console.log('src/hub/brandData.js written (font, logo, house)');
